"""Raw JSON/CSV -> cleaned CSVs (data/processed/) -> SQLite database (db/brickview.db).

    python pipeline.py
"""
import config
from src import clean, db


def main():
    print("1. Cleaning raw files ...")
    tables, log = clean.clean_all()
    config.PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    for name, df in tables.items():
        df.to_csv(config.PROCESSED_DIR / f"{name}.csv", index=False)
    log.to_csv(config.PROCESSED_DIR / "cleaning_log.csv", index=False)
    print(log.to_string(index=False))

    print("\n2. Building the database ...")
    counts = db.build(tables)
    for name, n in counts.items():
        print(f"   {name:<20} {n:>7,} rows")
    report = db.integrity_report()
    print(f"   foreign-key violations: {report['foreign_key_violations']}, "
          f"integrity check: {report['integrity_check']}")

    print("\n3. Running the 30 business queries ...")
    queries = db.load_queries()
    empty = [q["id"] for q in queries if db.query(q["sql"]).empty]
    print(f"   {len(queries)} queries ran, {len(empty)} empty {empty or ''}")

    (config.ROOT / "sql" / "schema_dump.sql").write_text(_schema_dump())
    print(f"\nDone -> {config.DB_PATH.relative_to(config.ROOT)}")


def _schema_dump():
    """The schema exactly as SQLite stores it (tables, indexes, views)."""
    with db.connect() as conn:
        rows = conn.execute(
            "SELECT sql FROM sqlite_master WHERE sql IS NOT NULL "
            "ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 ELSE 2 END, rowid").fetchall()
    return "-- Generated by pipeline.py from db/brickview.db\n\n" + ";\n\n".join(r[0] for r in rows) + ";\n"


if __name__ == "__main__":
    main()
